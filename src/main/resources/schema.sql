CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(255) NOT NULL UNIQUE,
  first_name VARCHAR(255),
  last_name VARCHAR(255),
  sur_name VARCHAR(255),
  avatar_media_key VARCHAR(1024),
  password VARCHAR(255) NOT NULL,
  nps DECIMAL(3,1) DEFAULT NULL CHECK (nps >= 0 AND nps <= 10.0),
  about TEXT,
  region VARCHAR(100) NOT NULL DEFAULT 'Другие регионы',
  company VARCHAR(255) NOT NULL DEFAULT 'Unknown',
  company_role VARCHAR(255),
  influence VARCHAR(20) NOT NULL DEFAULT 'local' CHECK (influence IN ('local', 'regional', 'federal', 'international')),
  profile_completion INTEGER NOT NULL DEFAULT 0 CHECK (profile_completion >= 0 AND profile_completion <= 100),
  audience INTEGER NOT NULL DEFAULT 0 CHECK (audience >= 0),
  last_evaluation_date TIMESTAMP,
  top_conference_candidate BOOLEAN NOT NULL DEFAULT FALSE,
  avatar_color VARCHAR(20) NOT NULL DEFAULT '#0ea5e9',
  created_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  last_modified_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_users_region ON users (region);
CREATE INDEX idx_users_company ON users (company);
CREATE INDEX idx_users_influence ON users (influence);

CREATE TABLE user_roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  role VARCHAR(50) NOT NULL CHECK (role IN ('ADMIN', 'DEVREL', 'SPEAKER', 'USER')),
  created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_user_roles_users_user_id FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT uq_user_roles_user_role UNIQUE (user_id, role)
);

CREATE INDEX idx_user_roles_user_id ON user_roles (user_id);

CREATE TABLE user_profile_tags (
  user_id BIGINT NOT NULL,
  tag VARCHAR(100) NOT NULL,
  created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_user_profile_tags PRIMARY KEY (user_id, tag),
  CONSTRAINT fk_user_profile_tags_users_user_id FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX idx_user_profile_tags_tag ON user_profile_tags (tag);

CREATE TABLE talks (
  id UUID PRIMARY KEY,
  speaker_id BIGINT NOT NULL,
  topic VARCHAR(255) NOT NULL,
  talk_date TIMESTAMP NOT NULL,
  conference_type VARCHAR(50) NOT NULL,
  format VARCHAR(50) NOT NULL,
  activity_name VARCHAR(255) NOT NULL,
  activity_date TIMESTAMP NOT NULL,
  created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_talks_users_speaker_id FOREIGN KEY (speaker_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX idx_talks_speaker_id ON talks (speaker_id);

CREATE TABLE talk_tags (
  talk_id UUID NOT NULL,
  tag VARCHAR(120) NOT NULL,
  created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_talk_tags PRIMARY KEY (talk_id, tag),
  CONSTRAINT fk_talk_tags_talk_id FOREIGN KEY (talk_id) REFERENCES talks(id) ON DELETE CASCADE
);

CREATE INDEX idx_talk_tags_tag ON talk_tags (tag);

CREATE TABLE lectures (
  id UUID PRIMARY KEY,
  title VARCHAR(500) NOT NULL,
  talk_id UUID NOT NULL,
  speaker_id BIGINT NOT NULL,
  media_s3_key VARCHAR(1024),
  created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_lectures_talks_talk_id FOREIGN KEY (talk_id) REFERENCES talks(id) ON DELETE CASCADE,
  CONSTRAINT fk_lectures_users_speaker_id FOREIGN KEY (speaker_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX idx_lectures_talk_id ON lectures (talk_id);
CREATE INDEX idx_lectures_speaker_id ON lectures (speaker_id);

CREATE TABLE talk_feedback (
  id UUID PRIMARY KEY,
  talk_id UUID NOT NULL,
  rating INTEGER NOT NULL CHECK (rating >= 0 AND rating <= 10),
  positive VARCHAR(4000) NOT NULL,
  negative VARCHAR(4000) NOT NULL,
  improvement_suggestions VARCHAR(4000) NOT NULL,
  created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_talk_feedback_talks_talk_id FOREIGN KEY (talk_id) REFERENCES talks(id) ON DELETE CASCADE
);

CREATE INDEX idx_talk_feedback_talk_id ON talk_feedback (talk_id);

CREATE TABLE speaker_roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  speaker_id BIGINT NOT NULL,
  created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_speaker_roles_users_speaker_id FOREIGN KEY (speaker_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX idx_speaker_roles_speaker_id ON speaker_roles (speaker_id);
CREATE INDEX idx_speaker_roles_name ON speaker_roles (name);

CREATE TABLE user_media (
  id UUID PRIMARY KEY,
  user_id BIGINT NOT NULL,
  media_minio_key VARCHAR(1024) NOT NULL UNIQUE,
  created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_user_media_users_user_id FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX idx_user_media_user_id ON user_media (user_id);

CREATE TABLE parsing_events (
  id UUID PRIMARY KEY,
  conference VARCHAR(255) NOT NULL,
  speaker_name VARCHAR(255) NOT NULL,
  company VARCHAR(255),
  source_url VARCHAR(1024) NOT NULL,
  event_date DATE NOT NULL,
  region VARCHAR(100),
  status VARCHAR(20) NOT NULL,
  speaker_id BIGINT,
  note TEXT,
  dedup_key VARCHAR(64) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_parsing_events_users_speaker_id FOREIGN KEY (speaker_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE UNIQUE INDEX idx_parsing_events_dedup ON parsing_events (dedup_key);
CREATE INDEX idx_parsing_events_event_date ON parsing_events (event_date);
CREATE INDEX idx_parsing_events_status ON parsing_events (status);

CREATE TABLE speaker_nps_history (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  speaker_id BIGINT NOT NULL,
  nps DECIMAL(3,1) NOT NULL CHECK (nps >= 0 AND nps <= 10.0),
  measured_at TIMESTAMP NOT NULL,
  source VARCHAR(50) NOT NULL DEFAULT 'manual',
  CONSTRAINT fk_speaker_nps_history_users_speaker_id FOREIGN KEY (speaker_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX idx_speaker_nps_history_speaker_id ON speaker_nps_history (speaker_id);
CREATE INDEX idx_speaker_nps_history_measured_at ON speaker_nps_history (measured_at);

CREATE TABLE speaker_achievements (
  id UUID PRIMARY KEY,
  speaker_id BIGINT NOT NULL,
  title VARCHAR(255) NOT NULL,
  description VARCHAR(1024) NOT NULL,
  current_value INTEGER NOT NULL CHECK (current_value >= 0),
  target_value INTEGER NOT NULL CHECK (target_value > 0),
  created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_speaker_achievements_users_speaker_id FOREIGN KEY (speaker_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX idx_speaker_achievements_speaker_id ON speaker_achievements (speaker_id);

CREATE TABLE cfp_recommendations (
  id UUID PRIMARY KEY,
  title VARCHAR(255) NOT NULL,
  city VARCHAR(100) NOT NULL,
  influence_level VARCHAR(20) NOT NULL,
  topic VARCHAR(255) NOT NULL,
  deadline DATE NOT NULL,
  host_company VARCHAR(255) NOT NULL,
  url VARCHAR(1024) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_cfp_recommendations_city ON cfp_recommendations (city);
CREATE INDEX idx_cfp_recommendations_influence_level ON cfp_recommendations (influence_level);
CREATE INDEX idx_cfp_recommendations_deadline ON cfp_recommendations (deadline);

CREATE TABLE cfp_recommendation_tags (
  recommendation_id UUID NOT NULL,
  tag VARCHAR(100) NOT NULL,
  created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT pk_cfp_recommendation_tags PRIMARY KEY (recommendation_id, tag),
  CONSTRAINT fk_cfp_recommendation_tags_recommendation_id FOREIGN KEY (recommendation_id) REFERENCES cfp_recommendations(id) ON DELETE CASCADE
);

CREATE INDEX idx_cfp_recommendation_tags_tag ON cfp_recommendation_tags (tag);

CREATE TABLE speaker_cfp_recommendations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  speaker_id BIGINT NOT NULL,
  recommendation_id UUID NOT NULL,
  match_score INTEGER NOT NULL CHECK (match_score >= 0 AND match_score <= 100),
  created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_speaker_cfp_recommendations_users_speaker_id FOREIGN KEY (speaker_id) REFERENCES users(id) ON DELETE CASCADE,
  CONSTRAINT fk_speaker_cfp_recommendations_recommendation_id FOREIGN KEY (recommendation_id) REFERENCES cfp_recommendations(id) ON DELETE CASCADE,
  CONSTRAINT uq_speaker_cfp_recommendations_pair UNIQUE (speaker_id, recommendation_id)
);

CREATE INDEX idx_speaker_cfp_recommendations_speaker_id ON speaker_cfp_recommendations (speaker_id);
CREATE INDEX idx_speaker_cfp_recommendations_match_score ON speaker_cfp_recommendations (match_score);

CREATE TABLE producer_plans (
  id UUID PRIMARY KEY,
  speaker_id BIGINT NOT NULL,
  status VARCHAR(30) NOT NULL CHECK (status IN ('ready', 'insufficient_data', 'failed')),
  plan_json TEXT,
  snapshot_json TEXT,
  validation_json TEXT,
  model VARCHAR(100),
  prompt_version VARCHAR(50),
  error TEXT,
  created_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_producer_plans_users_speaker_id FOREIGN KEY (speaker_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX idx_producer_plans_speaker_created ON producer_plans (speaker_id, created_date);
